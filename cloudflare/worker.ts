/**
 * Cloudflare Workers entry (wrangler.jsonc "main"). Wraps the OpenNext handler built by
 * `opennextjs-cloudflare build` and adds:
 *
 * 1. a Cloudflare Access check on every request (src/server/cloudflare/access.ts);
 * 2. a hard block on /api/internal/* from the outside;
 * 3. GenerationWorkflow: one durable Workflow instance per generation job. Its step calls the
 *    OpenNext handler in-process (no network hop) on POST /api/internal/generation/run with the
 *    isolate's internal token, so all generation code stays inside the Next.js bundle.
 */
import { WorkflowEntrypoint, type WorkflowEvent, type WorkflowStep } from "cloudflare:workers";
// Generated by `opennextjs-cloudflare build` (see cloudflare/open-next.d.ts).
import openNext from "../.open-next/worker.js";
import { verifyAccessRequest } from "../src/server/cloudflare/access";
import { INTERNAL_TOKEN_HEADER, ensureInternalToken } from "../src/server/cloudflare/internal-token";
// Prisma's query compiler as a precompiled module (workerd forbids compiling wasm at runtime);
// written by scripts/prepare-prisma-workerd.mjs, picked up by the patched generated client.
import prismaQueryCompiler from "../src/generated/prisma/internal/query_compiler.wasm";

(globalThis as Record<symbol, unknown>)[Symbol.for("job-hunter.prisma-query-compiler-wasm")] = prismaQueryCompiler;

interface GenerationParams {
  jobId: string;
  force?: boolean;
}

export default {
  async fetch(request, env, ctx) {
    const url = new URL(request.url);
    if (url.pathname.startsWith("/api/internal/")) return new Response("Not found", { status: 404 });

    const verdict = await verifyAccessRequest(request, env);
    if (!verdict.ok) {
      return Response.json(
        { error: verdict.reason, code: verdict.status === 503 ? "ACCESS_NOT_CONFIGURED" : "UNAUTHORIZED" },
        { status: verdict.status, headers: { "Cache-Control": "no-store" } },
      );
    }
    return openNext.fetch(request, env, ctx);
  },
} satisfies ExportedHandler<Env>;

export class GenerationWorkflow extends WorkflowEntrypoint<Env, GenerationParams> {
  async run(event: WorkflowEvent<GenerationParams>, step: WorkflowStep): Promise<{ status: string }> {
    const { jobId, force } = event.payload;
    return step.do(
      "run generation job",
      // A retry resumes the job: finished sections are skipped (input hash), a finished job is a no-op.
      { retries: { limit: 2, delay: "30 seconds", backoff: "exponential" }, timeout: "30 minutes" },
      async () => {
        const request = new Request("http://localhost/api/internal/generation/run", {
          method: "POST",
          // Created lazily: workerd forbids random values at global scope.
          // Synthetic requests carry no Host header; src/proxy.ts requires one (localhost is allowed).
          headers: {
            host: "localhost",
            "content-type": "application/json",
            [INTERNAL_TOKEN_HEADER]: ensureInternalToken(),
          },
          body: JSON.stringify({ jobId, force: force ?? false }),
        });
        const response = await openNext.fetch(request, this.env, this.ctx);
        if (!response.ok) {
          throw new Error(`Generation runner returned ${response.status}: ${(await response.text()).slice(0, 300)}`);
        }
        return (await response.json()) as { status: string };
      },
    );
  }
}
